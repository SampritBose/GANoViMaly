"""Evaluate frame-level anomaly scores against a ground-truth CSV."""
import argparse
import pandas as pd
from sklearn.metrics import roc_auc_score, roc_curve


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--scores", required=True, help="CSV generated by infer.py")
    parser.add_argument("--labels", required=True, help="CSV with frame_index,label (0 normal, 1 anomaly)")
    args = parser.parse_args()
    scores = pd.read_csv(args.scores)
    labels = pd.read_csv(args.labels)
    merged = scores.merge(labels[["frame_index", "label"]], on="frame_index", how="inner")
    if merged.empty:
        raise ValueError("No matching frame_index values between score and label CSVs.")
    if merged["label"].nunique() < 2:
        raise ValueError("AUC requires at least one normal and one anomalous frame.")
    auc = roc_auc_score(merged["label"], merged["anomaly_score"])
    fpr, tpr, thresholds = roc_curve(merged["label"], merged["anomaly_score"])
    fnr = 1.0 - tpr
    eer_idx = abs(fpr - fnr).argmin()
    print(f"Frames evaluated: {len(merged)}")
    print(f"Frame-level AUC: {auc:.4f}")
    print(f"Approximate EER: {(fpr[eer_idx] + fnr[eer_idx]) / 2:.4f}")


if __name__ == "__main__":
    main()
